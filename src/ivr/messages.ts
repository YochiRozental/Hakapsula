import type { Msg } from "yemot-router2";

/** להודעות שנשארות דינמיות בהכרח (שם חופשי שנאמר ע"י המתקשר, הודעת האישור עם התאריך/שעה, או הודעות שגיאה שמגיעות מלוגיקה עסקית משותפת עם האתר - src/lib/booking.ts) */
export function text(data: string): Msg {
  // מסירים בעצמנו את התווים ש-ימות לא מקבלת בהקראה (אותה קבוצה שהספרייה מסירה). כשהספרייה מסירה אותם בעצמה היא
  // רושמת בלוג את הטקסט המקורי, כולל שמות לקוחות (למשל עם גרש), ולכן אנחנו מנקים לפניה והתוצאה זהה להקראה
  return { type: "text", data: data.replaceAll(/[.\-"'&|]/g, ""), removeInvalidChars: true };
}
